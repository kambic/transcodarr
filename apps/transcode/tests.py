"""Tests for the transcode app.

Where ffmpeg is available these run against real, tiny clips generated by
lavfi — a stubbed subprocess would prove nothing about argument construction,
which is exactly the part most likely to be wrong.
"""

import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from django.core.files.base import ContentFile
from django.test import TestCase, override_settings
from django.urls import reverse

from explorer.models import Node, Operation, ScanRoot

from . import ffmpeg, services
from .models import MediaProbe, Preset, TranscodeJob

HAS_FFMPEG = shutil.which("ffmpeg") and shutil.which("ffprobe")
requires_ffmpeg = unittest.skipUnless(HAS_FFMPEG, "ffmpeg is not installed")


def make_clip(path: Path, seconds: int = 1, size: str = "320x240") -> Path:
    """A real, tiny video file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "ffmpeg", "-nostdin", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", f"testsrc=size={size}:rate=15:duration={seconds}",
            "-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}",
            "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-shortest", str(path),
        ],
        check=True,
        capture_output=True,
    )
    return path


class TranscodeTestCase(TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.base = Path(self.tmp.name)

        self.media_root = self.base / "media"
        self.work_dir = self.base / "work"
        self.share_dir = self.base / "share"
        self.share_dir.mkdir(parents=True, exist_ok=True)

        overrides = override_settings(
            MEDIA_ROOT=str(self.media_root),
            TRANSCODE={
                **self.settings_transcode(),
                "WORK_DIR": str(self.work_dir),
            },
        )
        overrides.enable()
        self.addCleanup(overrides.disable)

        self.root = Node.objects.create(name="My Drive", kind=Node.Kind.FOLDER)
        self.folder = Node.objects.create(parent=self.root, name="Footage", kind=Node.Kind.FOLDER)
        self.preset = Preset.objects.get(slug="proxy-480p")

    def settings_transcode(self):
        from django.conf import settings

        return dict(settings.TRANSCODE)

    def add_local_file(self, name="clip.mp4", parent=None, seconds=1):
        """A node whose bytes live in MEDIA_ROOT, like a browser upload."""
        source = make_clip(self.base / "src" / name, seconds=seconds)
        node = Node(parent=parent or self.folder, name=name, kind=Node.Kind.FILE)
        node.upload.save(name, ContentFile(source.read_bytes()), save=False)
        node.size = node.upload.size
        node.save()
        return node


