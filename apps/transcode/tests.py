@requires_ffmpeg
class RunTests(TranscodeTestCase):
    def test_probe_reads_real_metadata(self):
        node = self.add_local_file(seconds=1)
        probe = services.probe_node(node)
        self.assertEqual(probe.error, "")
        self.assertAlmostEqual(probe.duration_seconds, 1.0, delta=0.4)
        self.assertEqual((probe.width, probe.height), (320, 240))
        self.assertEqual(probe.video_codec, "h264")
        self.assertEqual(probe.audio_codec, "aac")

    def test_transcode_produces_a_playable_smaller_file(self):
        node = self.add_local_file(seconds=2)
        job = services.queue(nodes=[node], preset=self.preset)["queued"][0]

        job = services.run(services.claim(str(job.pk)))

        self.assertEqual(job.status, TranscodeJob.Status.DONE, job.error)
        self.assertEqual(job.progress, 100)
        self.assertIsNotNone(job.output)

        output = job.output
        self.assertEqual(output.name, "clip-proxy.mp4")
        self.assertEqual(output.parent, self.folder)
        self.assertTrue(Path(output.upload.path).exists())
        self.assertEqual(output.size, Path(output.upload.path).stat().st_size)

        # It's a real video, downscaled as the preset asked.
        result = ffmpeg.probe(output.upload.path)
        self.assertEqual(result.height, 240)  # source was smaller; never upscales
        self.assertTrue(result.has_video and result.has_audio)

    def test_source_is_left_alone(self):
        node = self.add_local_file()
        before = Path(node.upload.path).read_bytes()
        job = services.queue(nodes=[node], preset=self.preset)["queued"][0]
        services.run(services.claim(str(job.pk)))
        self.assertEqual(Path(node.upload.path).read_bytes(), before)
        self.assertTrue(Node.objects.filter(pk=node.pk).exists())

    def test_conversion_is_written_to_the_audit_log(self):
        node = self.add_local_file()
        job = services.queue(nodes=[node], preset=self.preset)["queued"][0]
        job = services.run(services.claim(str(job.pk)))

        operation = Operation.objects.get(kind=Operation.Kind.TRANSCODE)
        self.assertEqual(operation.status, Operation.Status.DONE)
        self.assertEqual(operation.items.get().node, job.output)
        self.assertFalse(operation.can_undo)
        self.assertEqual(operation.detail["preset"], "proxy-480p")

    def test_work_directory_is_left_clean(self):
        node = self.add_local_file()
        job = services.queue(nodes=[node], preset=self.preset)["queued"][0]
        services.run(services.claim(str(job.pk)))
        leftovers = list(self.work_dir.glob("job-*"))
        self.assertEqual(leftovers, [])

    def test_audio_extraction(self):
        node = self.add_local_file(seconds=1)
        preset = Preset.objects.get(slug="audio-m4a")
        job = services.queue(nodes=[node], preset=preset)["queued"][0]

        job = services.run(services.claim(str(job.pk)))

        self.assertEqual(job.status, TranscodeJob.Status.DONE, job.error)
        result = ffmpeg.probe(job.output.upload.path)
        self.assertFalse(result.has_video)
        self.assertTrue(result.has_audio)

    def test_a_non_media_file_fails_rather_than_producing_junk(self):
        node = Node(parent=self.folder, name="notes.mp4", kind=Node.Kind.FILE)
        node.upload.save("notes.mp4", ContentFile(b"this is not a video"), save=False)
        node.size = node.upload.size
        node.save()

        job = services.queue(nodes=[node], preset=self.preset)["queued"][0]
        job = services.run(services.claim(str(job.pk)))

        self.assertEqual(job.status, TranscodeJob.Status.FAILED)
        self.assertIn("ffprobe", job.error)
        self.assertIsNone(job.output)

    def test_cancellation_stops_a_running_job(self):
        """Cancel is checked mid-run, so a long encode stops promptly."""
        node = self.add_local_file(seconds=60)
        slow = Preset.objects.create(
            slug="slow-test", label="Slow", container="mp4",
            video_codec="libx264", crf=18, speed="veryslow", audio_codec="aac",
        )
        job = services.queue(nodes=[node], preset=slow)["queued"][0]
        TranscodeJob.objects.filter(pk=job.pk).update(cancel_requested=True)

        job = services.run(services.claim(str(job.pk)))

        self.assertEqual(job.status, TranscodeJob.Status.CANCELLED)
        self.assertIsNone(job.output)
        self.assertEqual(list(self.work_dir.glob("job-*")), [])

    def test_timeout_stops_a_runaway_encode(self):
        node = self.add_local_file(seconds=30)
        slow = Preset.objects.create(
            slug="slow-timeout", label="Slow", container="mp4",
            video_codec="libx265", crf=18, speed="veryslow", audio_codec="aac",
        )
        job = services.queue(nodes=[node], preset=slow)["queued"][0]

        with override_settings(TRANSCODE={**self.settings_transcode(),
                                          "WORK_DIR": str(self.work_dir),
                                          "MAX_JOB_SECONDS": 1}):
            job = services.run(services.claim(str(job.pk)))

        self.assertEqual(job.status, TranscodeJob.Status.FAILED)
        self.assertIn("limit", job.error)

    def test_task_entrypoint(self):
        from .tasks import run_transcode, transcode_nodes

        node = self.add_local_file()
        result = transcode_nodes.enqueue([str(node.pk)], "proxy-480p")
        self.assertEqual(result.return_value["queued"], 1)
        job = TranscodeJob.objects.get()
        self.assertEqual(job.status, TranscodeJob.Status.DONE, job.error)

        # Redelivery of the same task must not run it twice.
        again = run_transcode.enqueue(str(job.pk))
        self.assertFalse(again.return_value["claimed"])
        self.assertEqual(TranscodeJob.objects.count(), 1)

    def test_probe_pending_task(self):
        from .tasks import probe_pending

        self.add_local_file("a.mp4")
        Node.objects.create(parent=self.folder, name="b.pdf", size=5)
        self.assertEqual(probe_pending.enqueue().return_value, 1)
        self.assertEqual(MediaProbe.objects.count(), 1)


