class PresetTests(TestCase):
    def test_default_presets_are_installed(self):
        self.assertTrue(Preset.objects.filter(slug="web-1080p", enabled=True).exists())
        self.assertEqual(Preset.objects.count(), 7)

    def test_output_name_uses_suffix_and_container(self):
        preset = Preset.objects.get(slug="web-720p")
        self.assertEqual(preset.output_name("Beach Day.MOV"), "Beach Day-720p.mp4")

    def test_audio_preset_drops_video(self):
        preset = Preset.objects.get(slug="audio-m4a")
        args = ffmpeg.build_args(preset, "/in.mov", "/out.m4a")
        self.assertIn("-vn", args)
        self.assertIn("libmp3lame" if preset.slug == "audio-mp3" else "aac", args)

    def test_scale_filter_escapes_its_comma(self):
        preset = Preset.objects.get(slug="web-720p")
        args = ffmpeg.build_args(preset, "/in.mov", "/out.mp4")
        self.assertIn("scale=-2:min(ih\\,720)", args)

    def test_remux_preset_copies_streams_without_quality_flags(self):
        args = ffmpeg.build_args(Preset.objects.get(slug="remux-mp4"), "/in.mkv", "/out.mp4")
        self.assertEqual(args[args.index("-c:v") + 1], "copy")
        self.assertNotIn("-crf", args)

    def test_filenames_are_never_shell_interpreted(self):
        preset = Preset.objects.get(slug="web-720p")
        nasty = "/tmp/a b; rm -rf $HOME/'quote'.mov"
        args = ffmpeg.build_args(preset, nasty, "/out.mp4")
        self.assertIn(nasty, args)  # one argv element, not a shell string

    def test_preset_rejecting_both_streams(self):
        from django.core.exceptions import ValidationError

        preset = Preset(slug="x", label="X", video_codec="none", audio_codec="none")
        with self.assertRaises(ValidationError):
            preset.clean()

    def test_extra_args_must_be_strings(self):
        from django.core.exceptions import ValidationError

        with self.assertRaises(ValidationError):
            Preset(slug="y", label="Y", extra_args=[{"nope": 1}]).clean()

    def test_parse_frame_rate(self):
        self.assertEqual(ffmpeg.parse_rate("30000/1001"), 29.97)
        self.assertEqual(ffmpeg.parse_rate("25/1"), 25.0)
        self.assertEqual(ffmpeg.parse_rate("0/0"), 0.0)
        self.assertEqual(ffmpeg.parse_rate(None), 0.0)


