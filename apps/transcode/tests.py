class ViewTests(TranscodeTestCase):
    def test_choose_lists_presets_and_counts_eligible_files(self):
        video = Node.objects.create(parent=self.folder, name="a.mov", size=10)
        doc = Node.objects.create(parent=self.folder, name="a.pdf", size=10)

        response = self.client.get(
            reverse("transcode:choose"), {"ids": [str(video.pk), str(doc.pk)]}
        )

        self.assertContains(response, "Editing proxy 480p")
        self.assertContains(response, "1 media file")

    def test_choose_with_nothing_convertible(self):
        doc = Node.objects.create(parent=self.folder, name="a.pdf", size=10)
        response = self.client.get(reverse("transcode:choose"), {"ids": [str(doc.pk)]})
        self.assertContains(response, "Nothing in that selection")

    @requires_ffmpeg
    def test_start_queues_and_reports(self):
        node = self.add_local_file()
        response = self.client.post(
            reverse("transcode:start"), {"ids": [str(node.pk)], "preset": "proxy-480p"}
        )
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Queued 1 file")
        self.assertContains(response, "hx-swap-oob")  # the toast
        self.assertEqual(TranscodeJob.objects.count(), 1)

    def test_start_with_no_media_says_so(self):
        doc = Node.objects.create(parent=self.folder, name="a.pdf", size=10)
        response = self.client.post(
            reverse("transcode:start"), {"ids": [str(doc.pk)], "preset": "proxy-480p"}
        )
        self.assertContains(response, "No media files")
        self.assertEqual(TranscodeJob.objects.count(), 0)

    def test_panel_renders(self):
        self.assertEqual(self.client.get(reverse("transcode:panel")).status_code, 200)

    def test_cancel_view(self):
        node = Node.objects.create(parent=self.folder, name="a.mov", size=10)
        job = services.queue(nodes=[node], preset=self.preset)["queued"][0]
        response = self.client.post(reverse("transcode:cancel", args=[job.pk]))
        self.assertEqual(response.status_code, 200)
        self.assertEqual(TranscodeJob.objects.get(pk=job.pk).status, TranscodeJob.Status.CANCELLED)

    def test_explorer_offers_the_convert_action(self):
        response = self.client.get(reverse("explorer:index"))
        self.assertContains(response, reverse("transcode:choose"))
